require('dotenv').config();

// ── Detect which database to use ────────────────────────────────
// Oracle is used only when ORACLE_PASSWORD is set to a real value.
const useOracle =
    process.env.ORACLE_PASSWORD &&
    process.env.ORACLE_PASSWORD !== 'your_admin_password_here' &&
    process.env.ORACLE_CONNECTION_STRING;

let _execute;
let _init;

// ════════════════════════════════════════════════════════════════
// ORACLE PATH
// ════════════════════════════════════════════════════════════════
if (useOracle) {
    const oracledb = require('oracledb');
    oracledb.outFormat = oracledb.OUT_FORMAT_OBJECT;
    oracledb.autoCommit = true;

    let pool;

    const initPool = async () => {
        const config = {
            user:             process.env.ORACLE_USER || 'ADMIN',
            password:         process.env.ORACLE_PASSWORD,
            connectString:    process.env.ORACLE_CONNECTION_STRING,
            poolMin:          2,
            poolMax:          10,
            poolIncrement:    1,
        };
        if (process.env.ORACLE_WALLET_PATH) {
            config.walletLocation = process.env.ORACLE_WALLET_PATH;
            config.walletPassword = process.env.ORACLE_WALLET_PASSWORD || '';
        }
        pool = await oracledb.createPool(config);
        console.log('📡 [Oracle] Connection pool initialized.');
    };

    _execute = async (sql, binds = [], options = {}) => {
        let connection;
        try {
            connection = await pool.getConnection();
            const result = await connection.execute(sql, binds, {
                outFormat: oracledb.OUT_FORMAT_OBJECT,
                ...options,
            });
            return result;
        } finally {
            if (connection) await connection.close();
        }
    };

    const initSchema = async () => {
        console.log('🏗️  [Oracle] Initializing schema...');
        const tables = [
            {
                name: 'LOCATIONS',
                sql: `CREATE TABLE locations (
                    id   VARCHAR2(100) PRIMARY KEY,
                    name VARCHAR2(200) NOT NULL,
                    type VARCHAR2(50)  NOT NULL
                             CHECK(type IN ('industrial','residential','transit','school','commercial')),
                    lat  NUMBER NOT NULL,
                    lng  NUMBER NOT NULL
                )`,
            },
            {
                name: 'SENSOR_NODES',
                sql: `CREATE TABLE sensor_nodes (
                    id          VARCHAR2(100) PRIMARY KEY,
                    location_id VARCHAR2(100),
                    status      VARCHAR2(20) DEFAULT 'offline'
                                    CHECK(status IN ('online','offline')),
                    last_sync   VARCHAR2(50),
                    FOREIGN KEY (location_id) REFERENCES locations(id)
                )`,
            },
            {
                name: 'SENSOR_READINGS',
                sql: `CREATE TABLE sensor_readings (
                    id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    node_id          VARCHAR2(100) NOT NULL,
                    pm25             NUMBER, pm10 NUMBER, co NUMBER, nox NUMBER,
                    o3               NUMBER, voc_index NUMBER, temperature NUMBER,
                    humidity         NUMBER, oxygen NUMBER, pressure NUMBER,
                    aqi              NUMBER, aqi_category VARCHAR2(100),
                    air_quality_text CLOB,   rri NUMBER,
                    risk_level       VARCHAR2(50), risk_color VARCHAR2(20),
                    dominant         VARCHAR2(50),
                    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY (node_id) REFERENCES sensor_nodes(id)
                )`,
            },
            {
                name: 'USER_PROFILES',
                sql: `CREATE TABLE user_profiles (
                    id            VARCHAR2(100) PRIMARY KEY,
                    age_group     VARCHAR2(50), gender VARCHAR2(50),
                    asthma        NUMBER(1) DEFAULT 0,
                    smoking_level VARCHAR2(50), conditions CLOB,
                    multiplier    NUMBER DEFAULT 1.0
                )`,
            },
            {
                name: 'ALERTS',
                sql: `CREATE TABLE alerts (
                    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    type       VARCHAR2(100) NOT NULL,
                    message    CLOB          NOT NULL,
                    severity   VARCHAR2(20)  NOT NULL
                                   CHECK(severity IN ('info','warning','critical')),
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )`,
            },
        ];

        for (const table of tables) {
            try {
                await _execute(table.sql);
                console.log(`✅ [Oracle] Table ${table.name} created.`);
            } catch (err) {
                if (err.errorNum === 955) {
                    console.log(`ℹ️  [Oracle] Table ${table.name} already exists.`);
                } else {
                    throw err;
                }
            }
        }
        console.log('✅ [Oracle] Schema ready.');
    };

    _init = async () => {
        await initPool();
        await initSchema();
    };

// ════════════════════════════════════════════════════════════════
// SQLITE PATH (default / fallback)
// ════════════════════════════════════════════════════════════════
} else {
    const Database = require('better-sqlite3');
    const path = require('path');
    const fs   = require('fs');

    const dbPath = process.env.DB_PATH || './data/aeris.db';
    const dbDir  = path.dirname(dbPath);
    if (!fs.existsSync(dbDir)) fs.mkdirSync(dbDir, { recursive: true });

    const db = new Database(dbPath);
    db.pragma('journal_mode = WAL');

    // Normalize a row's keys to UPPERCASE to match Oracle behavior
    const normalize = (row) => {
        if (!row) return null;
        const out = {};
        for (const [k, v] of Object.entries(row)) out[k.toUpperCase()] = v;
        return out;
    };

    // Translate Oracle SQL dialect → SQLite
    const toSQLite = (sql) => sql
        .replace(/:(\d+)/g, '?')                                       // bind params
        .replace(/FETCH FIRST (\?) ROWS ONLY/gi, 'LIMIT ?')            // bind placeholder variant
        .replace(/FETCH FIRST (\d+) ROWS ONLY/gi, 'LIMIT $1');         // literal number variant

    // Wrap SQLite in an async interface that mirrors Oracle's { rows } shape
    _execute = async (sql, binds = []) => {
        const sqliteSQL = toSQLite(sql);
        const trimmed   = sqliteSQL.trim().toUpperCase();
        if (trimmed.startsWith('SELECT')) {
            const rows = db.prepare(sqliteSQL).all(...binds).map(normalize);
            return { rows };
        } else {
            const info = db.prepare(sqliteSQL).run(...binds);
            return { rows: [], rowsAffected: info.changes, lastInsertRowid: info.lastInsertRowid };
        }
    };

    const initSchema = () => {
        console.log('🏗️  [SQLite] Initializing schema...');
        db.exec(`
            CREATE TABLE IF NOT EXISTS locations (
                id   TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                type TEXT NOT NULL CHECK(type IN ('industrial','residential','transit','school','commercial')),
                lat  REAL NOT NULL,
                lng  REAL NOT NULL
            );
            CREATE TABLE IF NOT EXISTS sensor_nodes (
                id          TEXT PRIMARY KEY,
                location_id TEXT,
                status      TEXT DEFAULT 'offline' CHECK(status IN ('online','offline')),
                last_sync   TEXT,
                FOREIGN KEY (location_id) REFERENCES locations(id)
            );
            CREATE TABLE IF NOT EXISTS sensor_readings (
                id               INTEGER PRIMARY KEY AUTOINCREMENT,
                node_id          TEXT NOT NULL,
                pm25 REAL, pm10 REAL, co REAL, nox REAL, o3 REAL,
                voc_index REAL, temperature REAL, humidity REAL,
                oxygen REAL, pressure REAL, aqi INTEGER,
                aqi_category TEXT, air_quality_text TEXT, rri INTEGER,
                risk_level TEXT, risk_color TEXT, dominant TEXT,
                created_at TEXT DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (node_id) REFERENCES sensor_nodes(id)
            );
            CREATE TABLE IF NOT EXISTS user_profiles (
                id TEXT PRIMARY KEY, age_group TEXT, gender TEXT,
                asthma INTEGER DEFAULT 0, smoking_level TEXT,
                conditions TEXT, multiplier REAL DEFAULT 1.0
            );
            CREATE TABLE IF NOT EXISTS alerts (
                id         INTEGER PRIMARY KEY AUTOINCREMENT,
                type       TEXT NOT NULL,
                message    TEXT NOT NULL,
                severity   TEXT NOT NULL CHECK(severity IN ('info','warning','critical')),
                created_at TEXT DEFAULT CURRENT_TIMESTAMP
            );
        `);
        console.log('✅ [SQLite] Schema ready.');
    };

    _init = async () => {
        initSchema();
        console.log(`📡 [SQLite] Connected at ${dbPath}`);
    };
}

module.exports = { execute: _execute, init: _init };
